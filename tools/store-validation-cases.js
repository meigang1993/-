/* global assert */
module.exports = function assertInvalidOfflineSettlementData(store, validLocal) {
  [
    { _localClaimedBountyIds: "broken" },
    { _localDefeatIds: ["valid", null] },
    { _localInventoryOperationIds: [{}] },
    { _localInventoryRevision: -1 },
    { _localInventoryRevision: 1.5 },
    { shopAuthorityVersion: -1 },
    { shopAuthorityVersion: 1.5 },
    { _localDefeatCounter: -1 },
    { _localInventoryOperationCounter: 1.5 },
    { _localDefeatLedger: { version: 2, through: 0, legacy: [] } },
    { _localDefeatLedger: { version: 1, through: 0, legacy: ["raw-receipt"] } },
    { _localInventoryLedger: { version: 1, through: -1, legacy: [] } },
    { _localBountyClaimCounter: -1 },
    { _localBountyClaimCounter: 1.5 },
    { _localBountyClaimCounter: Number.MAX_SAFE_INTEGER + 1 },
    { _localBountyLedger: { through: -1, legacy: [] } },
    { _localBountyLedger: { through: 1.5, legacy: [] } },
    { _localBountyLedger: { through: Number.MAX_SAFE_INTEGER + 1, legacy: [] } },
    { _localBountyLedger: { version: -1, through: 0, legacy: [] } },
    { _localBountyLedger: { version: 2, through: 0, legacy: [] } },
    { _localBountyLedger: { through: 0, legacy: [null] } },
    { _localBountyLedger: { through: 0, legacy: ["raw-receipt"] } },
    { _localBountyLedger: { through: 0, legacy: ["x".repeat(10000)] } },
    { _localBountyLedger: { through: 0, legacy: Array(4097).fill("receipt") } },
    { _localRunState: [] },
    { _localRunState: { key: "", rewards: {} } },
    { _localRunState: { rewards: [] } },
    { _localRunState: { rewards: { receipt: null } } },
    { _localRunState: { version: 2, key: "run", rewards: {} } },
    { _localPendingRun: { gold: 10, essence: 0, cards: {}, relics: [] } },
    { pendingBountyRewards: {} },
    { pendingBountyRewards: [{ type: "essence", essence: 2 }, null] },
    { pendingBountyRewards: [{ reward: { type: "essence", essence: 2 }, bonusGold: 1_000_000_001 }] },
    { _pendingSettlementActions: [{ id: "x", type: "shopRefresh", attempts: -1, data: {} }] },
    { _pendingSettlementActions: [{ id: "x", type: "shopRefresh", lastError: {}, data: {} }] },
    { _pendingSettlementActions: Array.from({ length: 257 }, (_, index) => ({ id: `x${index}`, type: "shopRefresh", data: {} })) },
    { _pendingSettlementActions: [{ id: "x".repeat(201), type: "shopRefresh", data: {} }] },
    { _pendingSettlementActions: [{ id: "x", type: "s".repeat(65), data: {} }] },
    { _pendingSettlementActions: [{ id: "x", type: "shopRefresh", lastError: "x".repeat(501), data: {} }] },
  ].forEach(fields => {
    assert(store.inspectCopy({ ...validLocal, ...fields }).corrupt,
      `invalid offline settlement data should be rejected: ${Object.keys(fields)[0]}`);
  });
};
